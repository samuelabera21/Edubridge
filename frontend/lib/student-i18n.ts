export function useStudentLanguage() {
  const [lang, setLang] = useState<SupportedLanguage>("en");

  useEffect(() => {
    if (typeof window !== "undefined") {
      const saved = (localStorage.getItem("app_lang") || localStorage.getItem("student_lang")) as SupportedLanguage;
      if (saved && (saved === "en" || saved === "am" || saved === "om" || saved === "ti")) {
        setLang(saved);
      }
    }

    const handleLangChange = (e: any) => {
      if (e.detail && (e.detail === "en" || e.detail === "am" || e.detail === "om" || e.detail === "ti")) {
        setLang(e.detail);
      }
    };

    window.addEventListener("studentLanguageChange", handleLangChange);
    return () => window.removeEventListener("studentLanguageChange", handleLangChange);
  }, []);

  const changeLanguage = (newLang: SupportedLanguage) => {
    setLang(newLang);
    if (typeof window !== "undefined") {
      localStorage.setItem("app_lang", newLang);
      localStorage.setItem("student_lang", newLang);
      window.dispatchEvent(new CustomEvent("studentLanguageChange", { detail: newLang }));
    }
  };

  return {
    lang,
    t: translations[lang] || translations.en,
    changeLanguage,
  };
}
